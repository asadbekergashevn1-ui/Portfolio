import { writeFileSync } from 'node:fs';
export function writeReport(results, file) {
  const rows = Object.entries(results);
  const cap = rows.filter(([, r]) => r.status === 'captured');
  const no = rows.filter(([, r]) => r.status !== 'captured');
  let md = `# Capture report\n\nGenerated by \`capture/run.mjs\`. ${cap.length} captured, ${no.length} without a demo.\n\n`;
  md += `## Captured\n\n| Project | Shows | Demo | Card loop | Stills | Writes blocked |\n|---|---|---|---|---|---|\n`;
  for (const [slug, r] of cap) md += `| ${slug} | ${r.shows} | ${r.demoSeconds}s | ${r.previewSeconds}s | ${r.stills} | ${r.blockedWrites.length ? r.blockedWrites.map((w) => '`' + w + '`').join('<br>') : 'none attempted'} |\n`;
  md += `\n## Without a demo\n\n| Project | Why | What it would take |\n|---|---|---|\n`;
  for (const [slug, r] of no) md += `| ${slug} | ${r.reason} | ${r.needs} |\n`;
  md += `\n## Notes\n\n`;
  for (const [slug, r] of cap) for (const n of r.notes ?? []) md += `- **${slug}:** ${n}\n`;
  writeFileSync(file, md);
}
